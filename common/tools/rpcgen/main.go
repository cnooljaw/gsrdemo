// rpcgen 从节点 Service 附近的命令块生成共享 RPC 契约，仅处理显式声明的常量。
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"
)

const generatedHeader = "// Code generated by rpcgen; DO NOT EDIT.\n"

type command struct {
	name  string
	value string
}

type contract struct {
	name     string
	public   bool
	source   string
	service  string
	commands []command
}

func main() {
	root := flag.String("root", "..", "gsrdemo 根目录")
	check := flag.Bool("check", false, "只检查共享契约是否与源定义一致，不写文件")
	flag.Parse()
	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(root string, check bool) error {
	outputs := make(map[string][]byte)
	err := filepath.WalkDir(filepath.Join(root, "nodes"), func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		file, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.ParseComments)
		if err != nil {
			return err
		}
		for _, declaration := range file.Decls {
			block, ok := declaration.(*ast.GenDecl)
			if !ok || block.Doc == nil {
				continue
			}
			for _, comment := range block.Doc.List {
				if !strings.HasPrefix(comment.Text, "//rpc:service") {
					continue
				}
				relative, err := filepath.Rel(root, path)
				if err != nil {
					return err
				}
				definition, err := parseContract(block, comment.Text, filepath.ToSlash(relative))
				if err != nil {
					return fmt.Errorf("%s: %w", relative, err)
				}
				if !definition.public {
					continue
				}
				target := filepath.Join(root, "common", "rpc", definition.name, "commands.gen.go")
				if _, exists := outputs[target]; exists {
					return fmt.Errorf("%s: 公开 Service 契约名 %s 重复", relative, definition.name)
				}
				output, err := render(definition)
				if err != nil {
					return err
				}
				outputs[target] = output
			}
		}
		return nil
	})
	if err != nil {
		return err
	}
	return synchronize(root, outputs, check)
}

func parseContract(block *ast.GenDecl, marker, source string) (contract, error) {
	parts := strings.Fields(strings.TrimPrefix(marker, "//rpc:service "))
	if len(parts) < 2 || len(parts) > 3 || !validPackage(parts[0]) || (parts[1] != "public" && parts[1] != "private") {
		return contract{}, errors.New("标记格式应为 //rpc:service <包名> public|private [name=<本地名称常量>]")
	}
	definition := contract{name: parts[0], public: parts[1] == "public", source: source}
	nameConstant := ""
	if len(parts) == 3 {
		if !strings.HasPrefix(parts[2], "name=") || len(parts[2]) == len("name=") {
			return contract{}, errors.New("固定名称应写成 name=<本地名称常量>；动态实例省略此项")
		}
		nameConstant = strings.TrimPrefix(parts[2], "name=")
	}
	if block.Tok != token.CONST {
		return contract{}, errors.New("Service 命令必须定义在 const 块中")
	}
	ids := make(map[uint64]string)
	names := make(map[string]bool)
	for _, spec := range block.Specs {
		value, ok := spec.(*ast.ValueSpec)
		if !ok || len(value.Names) != 1 || len(value.Values) != 1 {
			return contract{}, errors.New("每项常量必须单独显式赋值，不能使用隐式递增")
		}
		name := value.Names[0].Name
		literal, ok := value.Values[0].(*ast.BasicLit)
		if !ok {
			return contract{}, fmt.Errorf("%s: 只支持显式字符串或整数，不支持 iota、引用或表达式", name)
		}
		if name == nameConstant {
			if literal.Kind != token.STRING {
				return contract{}, fmt.Errorf("%s: Service 名称必须是字符串", name)
			}
			service, err := strconv.Unquote(literal.Value)
			if err != nil || strings.TrimSpace(service) == "" {
				return contract{}, fmt.Errorf("%s: Service 名称不能为空", name)
			}
			definition.service = service
			continue
		}
		if literal.Kind != token.INT {
			return contract{}, fmt.Errorf("%s: 命令编号必须是 uint32 范围的显式整数", name)
		}
		id, err := strconv.ParseUint(strings.ReplaceAll(literal.Value, "_", ""), 0, 32)
		if err != nil {
			return contract{}, fmt.Errorf("%s: 无效的 CommandID: %w", name, err)
		}
		if previous, exists := ids[id]; exists {
			return contract{}, fmt.Errorf("Service %s 的命令 %s 与 %s 编号重复: %d", definition.name, name, previous, id)
		}
		ids[id] = name
		first, size := utf8.DecodeRuneInString(name)
		exported := string(unicode.ToUpper(first)) + name[size:]
		if exported == "ServiceName" || names[exported] || !ast.IsExported(exported) {
			return contract{}, fmt.Errorf("%s: 导出名称 %s 无效或重复", name, exported)
		}
		names[exported] = true
		definition.commands = append(definition.commands, command{name: exported, value: strconv.FormatUint(id, 10)})
	}
	if nameConstant != "" && definition.service == "" {
		return contract{}, fmt.Errorf("固定名称常量 %s 未在当前命令块定义", nameConstant)
	}
	if len(definition.commands) == 0 {
		return contract{}, errors.New("Service 命令块不能为空")
	}
	return definition, nil
}

func validPackage(name string) bool {
	if name == "main" || name == "_" || token.Lookup(name).IsKeyword() || name == "" {
		return false
	}
	for _, char := range name {
		if char < 'a' || char > 'z' {
			return false
		}
	}
	return true
}

func render(definition contract) ([]byte, error) {
	var output bytes.Buffer
	output.WriteString(generatedHeader)
	fmt.Fprintf(&output, "// Source: %s\n\npackage %s\n\n", definition.source, definition.name)
	if definition.service != "" {
		fmt.Fprintf(&output, "const ServiceName = %q\n\n", definition.service)
	}
	output.WriteString("const (\n")
	for _, command := range definition.commands {
		fmt.Fprintf(&output, "%s = %s\n", command.name, command.value)
	}
	output.WriteString(")\n")
	return format.Source(output.Bytes())
}

// synchronize 先核对全部目标的归属，检查模式不写文件；只清理本工具生成的过期文件。
func synchronize(root string, outputs map[string][]byte, check bool) error {
	paths := make(map[string]bool)
	for path := range outputs {
		paths[path] = true
	}
	err := filepath.WalkDir(filepath.Join(root, "common", "rpc"), func(path string, entry fs.DirEntry, err error) error {
		if errors.Is(err, fs.ErrNotExist) {
			return nil
		}
		if err != nil {
			return err
		}
		if !entry.IsDir() && entry.Name() == "commands.gen.go" {
			data, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if bytes.HasPrefix(data, []byte(generatedHeader)) {
				paths[path] = true
			}
		}
		return nil
	})
	if err != nil {
		return err
	}
	ordered := make([]string, 0, len(paths))
	for path := range paths {
		ordered = append(ordered, path)
	}
	sort.Strings(ordered)
	var changed []string
	for _, path := range ordered {
		current, err := os.ReadFile(path)
		if err != nil && !errors.Is(err, fs.ErrNotExist) {
			return err
		}
		if err == nil && !bytes.HasPrefix(current, []byte(generatedHeader)) {
			return fmt.Errorf("拒绝覆盖非 rpcgen 生成的文件: %s", path)
		}
		if !bytes.Equal(current, outputs[path]) {
			changed = append(changed, path)
		}
	}
	if check && len(changed) > 0 {
		return fmt.Errorf("RPC 契约未同步，请执行 ./scripts/dev.sh generate rpc: %s", strings.Join(changed, ", "))
	}
	for _, path := range changed {
		output, exists := outputs[path]
		if !exists {
			if err := os.Remove(path); err != nil {
				return err
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			return err
		}
		if err := os.WriteFile(path, output, 0644); err != nil {
			return err
		}
	}
	return nil
}
